function [cfg, traces] = build_final_inputs(cfg)
% Prepare derived settings and generate shared simulation inputs.
% This function does not run a controller.

assert(isfinite(cfg.dt) && cfg.dt > 0 && ...
       isfinite(cfg.simTime) && cfg.simTime > 0, ...
    'Invalid simulation timing.');

stepRatio = cfg.simTime / cfg.dt;

assert(abs(stepRatio - round(stepRatio)) < 1e-8, ...
    'Simulation duration must be an integer multiple of dt.');

cfg.numSteps = round(stepRatio);

assert(isfinite(cfg.queueCapacity) && ...
       cfg.queueCapacity >= 1 && ...
       cfg.queueCapacity == floor(cfg.queueCapacity), ...
    'Buffer capacity must be a positive integer.');

assert(isfinite(cfg.offeredLoad) && cfg.offeredLoad >= 0, ...
    'Offered load must be finite and nonnegative.');

assert(isfinite(cfg.packetBits) && cfg.packetBits > 0 && ...
       isfinite(cfg.linkRate_bps) && cfg.linkRate_bps >= 0, ...
    'Invalid packet size or link rate.');

% Recompute arrival rate after changing offered load.
cfg.arrivalRate_pps = ...
    cfg.offeredLoad * cfg.linkRate_bps / cfg.packetBits;

% Recompute thresholds after changing buffer or candidate fractions.
assert(cfg.redMinFraction > 0 && ...
       cfg.redMinFraction < cfg.redMaxFraction && ...
       cfg.redMaxFraction < 1, ...
    'Require 0 < minimum fraction < maximum fraction < 1.');

cfg.redMinTh = cfg.redMinFraction * cfg.queueCapacity;
cfg.redMaxTh = cfg.redMaxFraction * cfg.queueCapacity;

% Preserve the reference EWMA time scale.
assert(cfg.redReferenceDt > 0 && ...
       cfg.redReferenceWeight > 0 && ...
       cfg.redReferenceWeight < 1, ...
    'Invalid reference EWMA settings.');

cfg.redWeight = 1 - ...
    (1 - cfg.redReferenceWeight)^ ...
    (cfg.dt / cfg.redReferenceDt);

% This study uses duty cycles below one.
assert(isfinite(cfg.puDutyCycle) && ...
       cfg.puDutyCycle >= 0 && cfg.puDutyCycle < 1, ...
    'Require 0 <= PU duty cycle < 1.');

assert(isfinite(cfg.puMeanOn_s) && cfg.puMeanOn_s > 0, ...
    'Mean PU ON duration must be positive and finite.');

if cfg.puDutyCycle == 0
    cfg.puMeanOff_s = Inf;
else
    cfg.puMeanOff_s = cfg.puMeanOn_s * ...
        (1 - cfg.puDutyCycle) / cfg.puDutyCycle;
end

if lower(string(cfg.arrivalMode)) == "onoff"
    assert(cfg.trafficOnFraction > 0 && ...
           cfg.trafficOnFraction < 1 && ...
           isfinite(cfg.trafficMeanOn_s) && ...
           cfg.trafficMeanOn_s > 0, ...
        'Invalid burst-traffic settings.');

    cfg.trafficMeanOff_s = cfg.trafficMeanOn_s * ...
        (1 - cfg.trafficOnFraction) / ...
        cfg.trafficOnFraction;
end

% Preserve the caller's global random-number state.
previousRng = rng;
restoreRng = onCleanup(@() rng(previousRng));

% Each generator initializes its own reproducible randomness.
traces.puActual = generate_pu_trace(cfg);

[traces.sensed, traces.sensingSlot] = ...
    generate_sensed_pu_trace(traces.puActual, cfg);

traces.arrivals = generate_arrivals(cfg);

% Standardize trace shapes.
traces.puActual = logical(traces.puActual(:));
traces.sensed = logical(traces.sensed(:));
traces.sensingSlot = logical(traces.sensingSlot(:));
traces.arrivals = traces.arrivals(:);

assert(numel(traces.puActual) == cfg.numSteps && ...
       numel(traces.sensed) == cfg.numSteps && ...
       numel(traces.sensingSlot) == cfg.numSteps && ...
       numel(traces.arrivals) == cfg.numSteps, ...
    'Generated trace length mismatch.');
end